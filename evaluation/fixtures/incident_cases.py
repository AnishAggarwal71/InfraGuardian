"""
Incident-level fixtures for the M5 evaluation harness (PRD §10): one case per full
detect -> diagnose -> synthesize -> route run, with expected RCA domain, severity, and routing
decision.

Expected values are hand-derived from the actual breached-rule arithmetic in
`tools/thresholds.py`, the canned domain/severity/automation-safety table in `tools/llm.py`
(`_RULE_INFO`), the calibration formula in `tools/confidence.py`, and the routing gates in
`tools/routing.py` — traced by hand for each scenario's final sample, not generated by running
the pipeline and recording its output. See the inline derivation comments; this is what makes a
regression in any of those four modules show up as a harness failure instead of being
tautologically "correct" by construction.

These fixtures assume the default `FakeInfraGuardianModel` (PRD §10's accuracy numbers are
reported against it, not a real provider — see README/DECISIONS.md for why). They intentionally
don't attempt to cover every routing branch (e.g. confidence < 0.5, which never arises from any
real scenario's canned confidence) — `tests/test_routing.py` is the exhaustive branch-coverage
suite for that; this harness measures accuracy on realistic scenario fixtures instead.
"""

from __future__ import annotations

from pydantic import BaseModel

from agents.schemas import Domain, RoutingDecision, Severity
from tools.scenarios import SCENARIOS


class IncidentCase(BaseModel):
    """One end-to-end scenario (or scenario combination) with its expected incident outcome."""

    name: str
    scenario_names: list[str]
    expected_affected_domains: set[Domain]
    expected_rca_domain_keywords: dict[Domain, str]
    expected_severity: Severity
    expected_routing: RoutingDecision
    expected_runbook_id: str | None


def _final_samples(*scenario_names: str) -> dict[Domain, object]:
    samples = {}
    for name in scenario_names:
        final_sample = SCENARIOS[name][-1]
        samples[final_sample.domain] = final_sample
    return samples


